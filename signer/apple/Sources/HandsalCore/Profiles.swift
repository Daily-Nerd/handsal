// The editions of the profile set (CF-01, GP-07, GP-18, GP-22): their hashes, their fixture kid lists
// and the evaluation tables each one is read under.
//
// A profile hash is the hashstr of the canonical bytes of `{"core": <core manifest>, "kind": ...}`.
// An edition is one core manifest, so it has two hashes, a production one and a fixture one. The set
// is the frozen editions the catalog lists, oldest first, then the live core when it is not the last
// of them: the last edition is the current one, the only one a new organization is founded on (SG-17).
// `resolve` is the one question the rest of the signer asks about a hash: which edition, which kind,
// or nobody. No other file compares a profile hash with an edition's hash.
//
// The core manifest and the fixture kid list of the live core are copies of repository files (the
// signer has no JSON reader), so `ProfileTests` hashes the real files and fails when a copy is stale.
// Update the two tables below when that test says so. The frozen editions are generated by
// `tools/repin.py` between the two `handsal:editions` lines of `versions`: do not edit them by hand.
// A frozen edition is evaluated by the table of its registry file: `Registry.standard` when that file is the
// live one, else the table kept in `Registry.frozen` under its hash, which `RegistryGuardTests` compares with
// the frozen registry the block carries.

/// One frozen edition, as `tools/repin.py` writes it from `profiles/<label>/`.
struct FrozenEdition: Sendable {
    let label: String
    let production: String
    let fixture: String
    let coreManifest: [String: String]
    let fixtureKids: [String]
    let registryJSON: String
}

/// One edition of the set: the hashes of its two profiles, its fixture kids and its evaluation tables.
public struct Edition: Sendable {
    public let label: String
    public let production: String
    public let fixture: String
    public let fixtureKids: Set<String>
    public let registry: Registry

    public init(label: String, production: String, fixture: String, fixtureKids: Set<String>, registry: Registry) {
        self.label = label; self.production = production; self.fixture = fixture
        self.fixtureKids = fixtureKids; self.registry = registry
    }
}

public struct Profiles: Sendable {
    public enum Kind: Sendable { case production, fixture }

    /// The answer of `resolve`: the edition a hash belongs to, and which of its two profiles it is.
    public struct Match: Sendable {
        public let edition: Edition
        public let kind: Kind
    }

    /// Every supported edition in catalog order, oldest first; the last is the current one.
    public let editions: [Edition]

    public init(editions: [Edition]) {
        precondition(!editions.isEmpty, "the profile set has at least the live core")
        self.editions = editions
    }

    public var current: Edition { editions[editions.count - 1] }
    public var production: String { current.production }
    public var fixture: String { current.fixture }
    public var fixtureKids: Set<String> { current.fixtureKids }

    /// Every production profile hash the signer implements, in catalog order (SG-02).
    public var productionHashes: [String] { editions.map(\.production) }

    /// The edition and the kind of `hash`, or nil for a value that is no implemented profile.
    public func resolve(_ hash: String) -> Match? {
        for edition in editions {
            if hash == edition.production { return Match(edition: edition, kind: .production) }
            if hash == edition.fixture { return Match(edition: edition, kind: .fixture) }
        }
        return nil
    }

    /// Whether `hash` is the production profile of the current edition (SG-17).
    public func isCurrentProduction(_ hash: String) -> Bool { hash == current.production }

