    static func hash(_ kind: String, _ manifest: [String: String]) -> String {
        let core = JValue.object(manifest.mapValues { .string($0) })
        guard let bytes = try? Emit.subset(.object(["core": core, "kind": .string(kind)])) else {
            fatalError("the core manifest is not in the canonical subset")
        }
        return Encoding.hashstr(bytes)
    }

